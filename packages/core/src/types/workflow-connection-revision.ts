import type { z } from 'zod';
import type {
  workflowConnectionRevisionProposalSchema,
  workflowConnectionRevisionImpactSchema,
  workflowConnectionMaterialRepairRequestSchema,
  workflowConnectionMaterialRepairTargetSchema,
  workflowConnectionMaterialRepairReceiptSchema,
} from '../schemas/workflow-connection-revision-schema.js';
import type {
  WorkflowConnectionSessionInput,
  WorkflowConnectionSessionSource,
  WorkflowConnectionSession,
  WorkflowConnectionStepExpectation,
  WorkflowConnectionSessionDescription,
  WorkflowConnectionWorkingGraph,
  WorkflowConnectionInspection,
  WorkflowConnectionStepDescription,
  WorkflowConnectionGoalPlanningDescription,
  InspectWorkflowConnectionGraphResult,
} from './workflow-connection-session.js';
import type { WorkflowConnectionPlanningSnapshot } from './workflow-connection-planning.js';
import type { ReviewableWorkflowApiMaterial } from './reviewable-workflow.js';
import type { PlannedNativeNode } from './workflow-plan.js';
import type {
  WorkflowConnectionArgumentValues,
  WorkflowConnectionApiResponseContext,
} from './workflow-connection-material-repair.js';
import type { JsonObject } from './openapi.js';
import type { NativeOutputContract } from './node-output.js';
import type { NativePlanningCapabilityMaterial } from './native-node-planning.js';

export type WorkflowConnectionRevisionProposal = z.infer<
  typeof workflowConnectionRevisionProposalSchema
>;
export type WorkflowConnectionRevisionImpact = z.infer<
  typeof workflowConnectionRevisionImpactSchema
>;
export type WorkflowConnectionMaterialRepairRequest = z.infer<
  typeof workflowConnectionMaterialRepairRequestSchema
>;
export type WorkflowConnectionMaterialRepairTarget = z.infer<
  typeof workflowConnectionMaterialRepairTargetSchema
>;
export type WorkflowConnectionMaterialRepairReceipt = z.infer<
  typeof workflowConnectionMaterialRepairReceiptSchema
>;
export interface ValidateWorkflowConnectionMaterialRepairReceiptInput extends WorkflowConnectionRevisionInput {
  receipt: WorkflowConnectionMaterialRepairReceipt;
}
export interface ValidateWorkflowConnectionMaterialRepairInput extends WorkflowConnectionRevisionInput {
  request: WorkflowConnectionMaterialRepairRequest;
}

export interface ApplyWorkflowConnectionRevisionInput {
  before: WorkflowConnectionSessionInput;
  /** Reconstructed by the caller from actual planning results, not generated by the revision model. */
  after: WorkflowConnectionSessionSource;
  expected: WorkflowConnectionStepExpectation;
  proposal: WorkflowConnectionRevisionProposal;
}

export type WorkflowConnectionRevisionInput = Omit<
  ApplyWorkflowConnectionRevisionInput,
  'proposal'
>;

export interface WorkflowConnectionRevisionSourceDescription {
  before: WorkflowConnectionSessionDescription;
  after: WorkflowConnectionSessionDescription;
  expected: WorkflowConnectionStepExpectation;
}

export interface WorkflowConnectionRevisionDescription {
  /** Binds both source epochs, the original session history and the exact expectation. */
  sourceFingerprint: string;
  before: WorkflowConnectionStepDescription;
  after: WorkflowConnectionGoalPlanningDescription;
  nativeNodeIds: string[];
  materialChanges: WorkflowConnectionRevisionMaterialChanges;
  /** The unchanged current graph inspected against replacement contracts, not an executable candidate. */
  currentGraphInspection: WorkflowConnectionRevisionGraphInspection;
}

export type WorkflowConnectionRevisionGraphInspection = Omit<
  InspectWorkflowConnectionGraphResult,
  'routeStates'
>;

export interface WorkflowConnectionRevisionApiChange {
  callId: string;
  argumentsChanged: boolean;
  before: WorkflowConnectionArgumentValues;
  after: WorkflowConnectionArgumentValues;
  beforeRequestSchema: JsonObject;
  afterRequestSchema: JsonObject;
}
export interface WorkflowConnectionRevisionMaterialDescriptionInput extends WorkflowConnectionRevisionSourceDescription {
  session: WorkflowConnectionSession;
}
export interface WorkflowConnectionRevisionNativeChange {
  nodeId: string;
  before: PlannedNativeNode | null;
  after: PlannedNativeNode | null;
  beforeOutput: NativeOutputContract | null;
  afterOutput: NativeOutputContract | null;
  beforeDefinition: NativePlanningCapabilityMaterial | null;
  afterDefinition: NativePlanningCapabilityMaterial | null;
}
export interface WorkflowConnectionRevisionMaterialChanges {
  apiCalls: WorkflowConnectionRevisionApiChange[];
  nativeNodes: WorkflowConnectionRevisionNativeChange[];
  apiResponseContracts: WorkflowConnectionApiResponseContext[];
}

export interface WorkflowConnectionRevision {
  previous: WorkflowConnectionStepExpectation;
  previousSession: WorkflowConnectionSession;
  proposal: WorkflowConnectionRevisionProposal;
  session: WorkflowConnectionSession;
  impact: WorkflowConnectionRevisionImpact;
  inspection: WorkflowConnectionInspection;
  /** Explicit original-edge removals become the next epoch's baseline. */
  sourceUpdate: WorkflowConnectionRevisionSourceUpdate;
}

export interface WorkflowConnectionRevisionSourceUpdate {
  edges: WorkflowConnectionPlanningSnapshot['edges'];
  editableEdgeIds?: NonNullable<
    WorkflowConnectionSessionSource['editableEdgeIds']
  >;
}

export interface ValidateWorkflowConnectionRevisionInput extends ApplyWorkflowConnectionRevisionInput {
  revision: WorkflowConnectionRevision;
}

export interface AnalyzeWorkflowConnectionRevisionImpactInput {
  before: WorkflowConnectionSessionDescription;
  after: WorkflowConnectionSessionDescription;
  previousSession: WorkflowConnectionSession;
  goals: WorkflowConnectionSession['goals'];
  graph: WorkflowConnectionWorkingGraph;
}

export type WorkflowConnectionRevisionNode =
  ReviewableWorkflowApiMaterial | PlannedNativeNode;

export interface WorkflowConnectionRevisionNodeMapInput {
  snapshot: WorkflowConnectionPlanningSnapshot;
}
